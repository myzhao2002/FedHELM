def localize(app, title):
    app.title = title
    app.description = 'FedHELM中文接口文档。大小语言模型保留替身，轻量模型支持真实PyTorch训练。点击接口查看输入输出，使用“Try it out”进行测试。'
    for route in app.routes:
        if route.path in LABELS:
            route.summary, route.description = LABELS[route.path]
            route.tags = ['模块接口']
    app.openapi_schema = None
